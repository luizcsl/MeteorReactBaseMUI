import fs from 'node:fs';
import path from 'node:path';
import ts from 'typescript';
import { confined, exact, fail, files, hash, validateSpec } from './lib.mjs';
import { renderDefinition, validateDefinition } from './recipes.mjs';
import { renderExtensions } from './automation/generators/feature.mjs';
const json = (value) => JSON.stringify(value, null, 2) + '\n';
const base = 'imports/integration';
const header = '// Generated by module:integrate. Edit the integration specification, then replan.\n';
const moduleName = (name) => {
	if (typeof name !== 'string' || !/^[a-z][a-z0-9]{2,31}$/.test(name))
		fail('integration-module', 'Invalid module name');
};
export function validateIntegration(value) {
	exact(value, ['schemaVersion', 'module', 'label']);
	moduleName(value.module);
	if (value.schemaVersion !== 1 || typeof value.label !== 'string' || !value.label.trim() || value.label.length > 100)
		fail('integration-schema', 'Invalid integration specification');
	return structuredClone(value);
}
function snapshot(root, relative) {
	const directory = confined(root, relative);
	const names = files(directory);
	if (names.length > 500) fail('integration-budget', 'Too many integration/module files');
	let bytes = 0;
	return Object.fromEntries(
		names.map((name) => {
			const file = confined(directory, name),
				stat = fs.statSync(file);
			bytes += stat.size;
			if (bytes > 8 * 1024 * 1024) fail('integration-budget', 'Integration/module exceeds 8 MiB');
			return [`${relative}/${name}`, hash(fs.readFileSync(file))];
		})
	);
}
function readMetadata(root, file) {
	const target = confined(root, file),
		stat = fs.statSync(target);
	if (!stat.isFile() || stat.size > 1024 * 1024)
		fail('integration-budget', 'Metadata exceeds 1 MiB or is not a file', file);
	try {
		return JSON.parse(fs.readFileSync(target, 'utf8'));
	} catch {
		fail('integration-schema', 'Expected valid metadata JSON', file);
	}
}
function moduleInfo(root, name) {
	moduleName(name);
	const relative = `imports/modules/${name}`;
	const manifest = readMetadata(root, relative + '/module.manifest.json');
	let generated;
	let kind,
		page,
		services,
		workflow = false,
		relationships = false;
	if (manifest.templateVersion === '2.0.0') {
		const definition = validateDefinition(readMetadata(root, relative + '/module.definition.json'));
		if (definition.name !== name || manifest.definitionHash !== hash(json(definition)))
			fail('integration-manifest', 'Definition hash/identity mismatch');
		if (definition.profile === 'master-detail') {
			confined(root, `${relative}/custom/ui/Page.tsx`);
			page = 'custom/ui/Page';
		}
		generated = renderDefinition(definition);
		kind = 'recipe';
	} else if (
		manifest.templateVersion === '1.0.0' &&
		manifest.spec?.profile === 'owner-crud' &&
		manifest.spec.name === name
	) {
		const spec = validateSpec(manifest.spec),
			templateRoot = confined(root, 'templates/owner-crud/v1');
		const template = readMetadata(templateRoot, 'template.json');
		const names = files(confined(templateRoot, 'files'));
		if (names.length !== Object.keys(template.sha256).length)
			fail('integration-template', 'Template file set mismatch');
		const replace = (text) =>
			text
				.replace(/__MODULE_UPPER__/g, spec.name.toUpperCase())
				.replace(/__MODULE__/g, spec.name)
				.replace(/__Module__/g, spec.name[0].toUpperCase() + spec.name.slice(1));
		generated = Object.fromEntries(
			names.map((file) => {
				const content = fs.readFileSync(confined(templateRoot, `files/${file}`), 'utf8');
				if (hash(content) !== template.sha256[file]) fail('integration-template', 'Template hash mismatch');
				return [replace(file).replace(/\.template$/, ''), replace(content)];
			})
		);
		kind = 'owner';
	} else
		fail(
			'integration-profile',
			'Only versioned owner-crud and standalone recipes are supported; legacy modules require manual integration'
		);
	if (manifest.schemaVersion !== 1 || json(Object.keys(manifest.files).sort()) !== json(Object.keys(generated).sort()))
		fail('integration-manifest', 'Generated file set mismatch');
	for (const [file, content] of Object.entries(generated))
		if (
			manifest.files[file] !== hash(content) ||
			hash(fs.readFileSync(confined(root, `${relative}/${file}`))) !== hash(content)
		)
			fail('integration-drift', `Generated drift: ${relative}/${file}`);
	// Optional deterministic UI extensions have their own verified manifest; base generated files stay intact.
	if (fs.existsSync(confined(root, `${relative}/module.automation.json`, { missing: true }))) {
		const extension = readMetadata(root, `${relative}/module.automation.json`);
		exact(extension, ['schemaVersion', 'definitionHash', 'page', 'feature', 'files']);
		if (
			kind !== 'recipe' ||
			extension.schemaVersion !== 1 ||
			extension.definitionHash !== manifest.definitionHash ||
			extension.page !== 'automation/Page'
		)
			fail('integration-extension', 'Invalid automation extension');
		if (
			!extension.files ||
			typeof extension.files !== 'object' ||
			Array.isArray(extension.files) ||
			!Object.hasOwn(extension.files, 'automation/Page.tsx')
		)
			fail('integration-extension', 'Missing extension page');
		for (const [file, expected] of Object.entries(extension.files)) {
			if (
				!/^(?:generated|automation)\//.test(file) ||
				typeof expected !== 'string' ||
				hash(fs.readFileSync(confined(root, `${relative}/${file}`))) !== expected
			)
				fail('integration-extension', 'Extension drift or unsafe path', file);
		}
		const definition = validateDefinition(readMetadata(root, `${relative}/module.definition.json`));
		const expected = renderExtensions(definition, extension.feature, root);
		for (const [file, content] of Object.entries(expected))
			if (fs.readFileSync(confined(root, file), 'utf8') !== content)
				fail('integration-extension', 'Extension differs from deterministic generator', file);
		if (definition.profile !== 'master-detail') page = extension.page;
		workflow = Boolean(extension.feature.workflow);
		relationships = Boolean(extension.feature.relationships);
		if (
			relationships &&
			!fs.existsSync(confined(root, `${relative}/custom/server/relationshipPorts.ts`, { missing: true }))
		)
			fail(
				'needs-review',
				'Supply reviewed relationshipPorts.ts using the transactional registry',
				`${relative}/custom/server/relationshipPorts.ts`
			);
		if (Object.hasOwn(extension.files, 'generated/services/registration.json')) {
			services = readMetadata(root, `${relative}/generated/services/registration.json`);
			if (services.requiredAdapters.length) confined(root, `${relative}/custom/server/servicePorts.ts`);
		}
	}
	// Business identity and acceptance are deliberately supplied by reviewed custom code.
	for (const file of ['custom/server/ports.ts', 'custom/server/acceptance.test.ts'])
		confined(root, `${relative}/${file}`);
	return {
		name,
		kind,
		services,
		workflow,
		relationships,
		page: page ?? (kind === 'recipe' ? 'generated/Page' : `ui/${name[0].toUpperCase() + name.slice(1)}Page`),
		upper: name[0].toUpperCase() + name.slice(1),
		hashes: snapshot(root, relative)
	};
}
export function renderIntegration(root, entries) {
	const info = entries.map((entry) => ({ ...entry, ...moduleInfo(root, entry.module) }));
	const routes = info.map((m, i) => `import Page${i} from '../modules/${m.name}/${m.page}';`).join('\n');
	const server = info
		.map(
			(m, i) =>
				`import { register${m.upper} } from '../../modules/${m.name}/${m.kind === 'recipe' ? 'generated/server/register' : 'server/register'}';\nimport { ${m.kind === 'recipe' ? 'ports' : 'context'} as ports${i} } from '../../modules/${m.name}/custom/server/ports';` +
				(m.workflow
					? `\nimport { createWorkflowPorts as workflowPorts${i} } from '../../modules/${m.name}/generated/workflow/server';`
					: '') +
				(m.relationships
					? `\nimport { createRelationshipPorts as relationshipPorts${i} } from '../../modules/${m.name}/generated/relationships/server';\nimport { relationshipAdapter as relationshipAdapter${i} } from '../../modules/${m.name}/custom/server/relationshipPorts';`
					: '') +
				(m.services
					? `\nimport { registerServices as registerServices${i} } from '../../modules/${m.name}/generated/services/server/register';` +
						(m.services.requiredAdapters.length
							? `\nimport { serviceAdapters as serviceAdapters${i} } from '../../modules/${m.name}/custom/server/servicePorts';`
							: '')
					: '')
		)
		.join('\n');
	return {
		'registry.json': json({ schemaVersion: 1, entries }),
		'routes.tsx':
			header +
			`import type { IRoute, IAppMenu } from '../modules/modulesTypings';\n${routes}\nexport const integratedRoutes: IRoute[] = [${info.map((m, i) => `{path:'/modules/${m.name}',component:Page${i},isProtected:true,authenticatedOnly:true}`).join(',')}];\nexport const integratedMenu: IAppMenu[] = ${JSON.stringify(info.map((m) => ({ path: `/modules/${m.name}`, name: m.label, isProtected: true })))};\n`,
		'server/register.ts':
			header +
			`${server}\nexport function registerIntegratedModules(): void {\n${info
				.map((m, i) => {
					let ports = `ports${i}`;
					if (m.workflow) ports = `workflowPorts${i}(${ports})`;
					if (m.relationships) ports = `relationshipPorts${i}(${ports}, relationshipAdapter${i})`;
					return m.services
						? `const servicePorts${i}=register${m.upper}(${ports});\nregisterServices${i}(servicePorts${i}${m.services.requiredAdapters.length ? ', serviceAdapters' + i : ''});`
						: `register${m.upper}(${ports});`;
				})
				.join('\n')}\n}\n`,
		'server/tests.ts':
			header +
			info
				.map(
					(m) =>
						`import '../../modules/${m.name}/custom/server/acceptance.test';\n` +
						(m.kind === 'owner'
							? `import '../../modules/${m.name}/tests/policy.test';\n`
							: `import { verify${m.upper}Contract } from '../../modules/${m.name}/generated/contract.test';\ndescribe('${m.name} generated contract', () => { it('rejects forged fields', verify${m.upper}Contract); });\n`)
				)
				.join('')
	};
}
function routeCollisions(root, entries) {
	const preconditions = {};
	let routingBytes = 0;
	// Read routing declarations with the TS parser, including legacy config files.
	for (const file of files(confined(root, 'imports')).filter(
		(f) => /\.tsx?$/.test(f) && !f.startsWith('integration/') && !f.startsWith('.integration-')
	)) {
		const relative = 'imports/' + file;
		if (!/(?:Routers?|routes?|modules\/index)\./i.test(file)) continue;
		const target = confined(root, relative),
			stat = fs.statSync(target);
		routingBytes += stat.size;
		if (!stat.isFile() || stat.size > 1024 * 1024 || routingBytes > 8 * 1024 * 1024)
			fail('integration-budget', 'Routing sources exceed bounded inspection', relative);
		const source = fs.readFileSync(target, 'utf8');
		preconditions[relative] = hash(source);
		const ast = ts.createSourceFile(relative, source, ts.ScriptTarget.Latest, true);
		if (ast.parseDiagnostics.length) fail('integration-route', 'Invalid routing source', relative);
		function visit(node) {
			if (
				(ts.isPropertyAssignment(node) && ts.isComputedPropertyName(node.name)) ||
				(ts.isShorthandPropertyAssignment(node) && node.name.text === 'path')
			)
				fail('integration-route', 'Computed route metadata requires manual review', relative);
			if (ts.isPropertyAssignment(node) && node.name.getText(ast).replace(/['"]/g, '') === 'path') {
				if (!ts.isStringLiteral(node.initializer))
					fail('integration-route', `Computed route requires manual review: ${relative}`);
				const existing = node.initializer.text.split('/').filter(Boolean);
				for (const entry of entries) {
					const proposed = ['modules', entry.module];
					if (
						existing
							.slice(0, 2)
							.every((segment, i) => segment === '*' || segment.startsWith(':') || segment === proposed[i]) &&
						(existing.length >= 2 || existing[0] === '*')
					)
						fail('integration-collision', `Route collision in ${relative}`);
				}
			}
			ts.forEachChild(node, visit);
		}
		visit(ast);
	}
	return preconditions;
}
export function planIntegration(root, raw) {
	const input = validateIntegration(raw);
	const current = readMetadata(root, base + '/registry.json');
	exact(current, ['schemaVersion', 'entries']);
	if (current.schemaVersion !== 1 || !Array.isArray(current.entries) || current.entries.length > 100)
		fail('integration-registry', 'Invalid registry');
	const names = new Set();
	for (const entry of current.entries) {
		validateIntegration(entry);
		if (names.has(entry.module)) fail('integration-collision', 'Duplicate module');
		names.add(entry.module);
	}
	const before = snapshot(root, base);
	const expected = renderIntegration(root, current.entries);
	if (Object.keys(before).length !== Object.keys(expected).length)
		fail('integration-drift', 'Unexpected integration files');
	for (const [file, content] of Object.entries(expected))
		if (before[`${base}/${file}`] !== hash(content)) fail('integration-drift', `Integration customization: ${file}`);
	const entries = [...current.entries.filter((e) => e.module !== input.module), input].sort((a, b) =>
		a.module.localeCompare(b.module, 'en')
	);
	const output = renderIntegration(root, entries);
	const preconditions = { ...before, ...routeCollisions(root, entries) };
	for (const file of ['tools/integrate.mjs', 'tools/recipes.mjs', 'imports/core/recipes/definition.ts']) {
		const target = confined(root, file, { missing: true });
		if (fs.existsSync(target)) preconditions[file] = hash(fs.readFileSync(target));
	}
	if (entries.some((entry) => moduleInfo(root, entry.module).kind === 'owner'))
		Object.assign(preconditions, snapshot(root, 'templates/owner-crud/v1'));
	for (const entry of entries) Object.assign(preconditions, moduleInfo(root, entry.module).hashes);
	const changes = Object.entries(output)
		.filter(([file, content]) => before[`${base}/${file}`] !== hash(content))
		.map(([file, content]) => ({
			file: `${base}/${file}`,
			before: before[`${base}/${file}`],
			after: hash(content),
			content,
			diff: `--- a/${base}/${file}\n+++ b/${base}/${file}\n${fs
				.readFileSync(confined(root, `${base}/${file}`), 'utf8')
				.split('\n')
				.map((line) => '-' + line)
				.join('\n')}\n${content
				.split('\n')
				.map((line) => '+' + line)
				.join('\n')}`
		}));
	return {
		schemaVersion: 1,
		input,
		preconditions,
		changes,
		qualified: false,
		notice:
			'Wiring prepared only. Run doctor, typecheck, toolkit, verify and the real browser journey. No qualification or business permission is granted by applying a plan.'
	};
}
export function applyIntegration(root, plan) {
	const lock = confined(root, 'imports/.integration.lock', { missing: true });
	let fd;
	try {
		fd = fs.openSync(lock, 'wx');
	} catch (error) {
		if (error.code === 'EEXIST')
			fail('integration-locked', 'Integration locked; inspect interrupted writer before retrying');
		throw error;
	}
	let stage,
		backup,
		swapped = false;
	try {
		if (json(planIntegration(root, plan?.input)) !== json(plan))
			fail('integration-stale', 'Plan is stale or modified; regenerate');
		if (!plan.changes.length) return { status: 'unchanged', qualified: false };
		stage = fs.mkdtempSync(confined(root, 'imports/.integration-stage-', { missing: true }));
		const output = renderIntegration(root, readEntries(plan));
		for (const [file, content] of Object.entries(output)) {
			const target = confined(stage, file, { missing: true });
			fs.mkdirSync(path.dirname(target), { recursive: true });
			fs.writeFileSync(target, content, { flag: 'wx' });
		}
		if (json(planIntegration(root, plan.input)) !== json(plan))
			fail('integration-stale', 'Sources changed during staging');
		backup = stage + '.backup';
		fs.writeFileSync(fd, json({ stage, backup, preconditions: plan.preconditions }));
		fs.fsyncSync(fd);
		fs.renameSync(confined(root, base), backup);
		swapped = true;
		try {
			fs.renameSync(stage, path.join(root, base));
			stage = undefined;
		} catch (error) {
			fs.renameSync(backup, path.join(root, base));
			swapped = false;
			throw error;
		}
		fs.rmSync(backup, { recursive: true });
		swapped = false;
		return {
			status: 'applied',
			module: plan.input.module,
			route: `/modules/${plan.input.module}`,
			qualified: false,
			requiredGates: ['doctor', 'typecheck', 'test:toolkit', 'verify', 'test:browser']
		};
	} finally {
		fs.closeSync(fd);
		if (!swapped) {
			if (stage) fs.rmSync(stage, { recursive: true, force: true });
			fs.rmSync(lock, { force: true });
		}
	}
}
function readEntries(plan) {
	const change = plan.changes.find((c) => c.file === base + '/registry.json');
	return JSON.parse(change.content).entries;
}
